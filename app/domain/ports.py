"""Ports: abstractions (Protocols) the application layer depends on.

`app.infra` provides the adapters; `app.di` wires them. Nothing in `domain` or `application`
imports `infra`.
"""

from collections.abc import AsyncIterator
from typing import Protocol
from uuid import UUID

from app.domain.entities import Chunk, Collection
from app.domain.value_objects import ChatMessage, LLMProviderInfo


class Embedder(Protocol):
    async def embed_documents(self, texts: list[str]) -> list[list[float]]: ...
    async def embed_query(self, text: str) -> list[float]: ...
    async def healthcheck(self) -> bool: ...
    async def close(self) -> None: ...


class Reranker(Protocol):
    async def rerank(self, query: str, documents: list[str]) -> list[float]:
        """Return one relevance score per document, in input order."""
        ...

    async def healthcheck(self) -> bool: ...
    async def close(self) -> None: ...


class LLMClient(Protocol):
    provider: str
    model: str

    async def generate(self, system: str, messages: list[ChatMessage]) -> str: ...
    def stream(self, system: str, messages: list[ChatMessage]) -> AsyncIterator[str]: ...


class LLMClientFactory(Protocol):
    """Creates LLM clients on demand (the provider/model can be chosen per request)."""

    def create(self, provider: str | None = None, model: str | None = None) -> LLMClient: ...
    def default_provider(self) -> str: ...
    def providers(self) -> list[LLMProviderInfo]: ...


class VectorStore(Protocol):
    """The single persistence layer: collections, chunks (text + payload) and vectors."""

    name: str

    async def create_collection(self, collection: str, dim: int) -> None: ...
    async def delete_collection(self, collection: str) -> None: ...
    async def collection_exists(self, collection: str) -> bool: ...
    async def list_collections(self) -> list[Collection]: ...
    async def count(self, collection: str) -> int: ...

    async def upsert(self, collection: str, chunks: list[Chunk], vectors: list[list[float]]) -> None: ...
    async def search(self, collection: str, vector: list[float], top_k: int) -> list[tuple[Chunk, float]]:
        """Return (chunk, cosine similarity) pairs, best first."""
        ...

    async def list_chunks(self, collection: str, document_id: UUID | None = None) -> list[Chunk]: ...
    async def delete_document(self, collection: str, document_id: UUID) -> None: ...
    async def delete_chunks(self, collection: str, chunk_ids: list[UUID]) -> None: ...

    async def healthcheck(self) -> bool: ...
    async def close(self) -> None: ...


class LexicalIndex(Protocol):
    """Keyword (BM25) search over the chunks of a collection."""

    def invalidate(self, collection: str) -> None: ...
    async def search(self, collection: str, query: str, top_k: int) -> list[Chunk]:
        """Chunks ranked best first."""
        ...


class DocumentParser(Protocol):
    def supported_extensions(self) -> list[str]: ...

    def parse(self, filename: str, data: bytes) -> list[tuple[str, dict]]:
        """Load a file and split it into (text, metadata) chunks."""
        ...

    def parse_url(self, url: str) -> tuple[str, list[tuple[str, dict]]]:
        """Load a web page and split it. Returns (title, chunks). Blocking."""
        ...

    def split_text(self, text: str, metadata: dict) -> list[tuple[str, dict]]: ...


class UrlResolver(Protocol):
    async def resolve(self, url: str) -> str:
        """SSRF guard: validate the URL and its redirects, return the final safe URL."""
        ...
